import os
import re
import sqlite3
from contextlib import contextmanager
from pathlib import Path
from typing import Any, Generator

import psycopg
from dotenv import load_dotenv

PROJECT_DIR = Path(__file__).resolve().parent
load_dotenv(PROJECT_DIR / ".env")

DB_PATH = Path(
    os.environ.get(
        "KBW_B2_MONITOR_DB",
        PROJECT_DIR / "data" / "examens_b2_monitor.db",
    )
)


class DatabaseConnection:
    def __init__(self, connection: Any, postgres: bool) -> None:
        self._connection = connection
        self._postgres = postgres

    def execute(
        self,
        query: str,
        parameters: tuple[Any, ...] = (),
    ) -> Any:
        if self._postgres:
            query = query.replace("?", "%s")
        return self._connection.execute(query, parameters)

    def executemany(
        self,
        query: str,
        parameters: list[dict[str, Any]] | list[tuple[Any, ...]],
    ) -> Any:
        if self._postgres:
            if parameters and isinstance(parameters[0], dict):
                query = re.sub(r":([A-Za-z_]\w*)", r"%(\1)s", query)
            else:
                query = query.replace("?", "%s")
        return self._connection.executemany(query, parameters)


@contextmanager
def connect_db() -> Generator[DatabaseConnection, None, None]:
    database_url = os.environ.get("SUPABASE_DB_URL", "").strip()

    if database_url:
        with psycopg.connect(database_url) as connection:
            yield DatabaseConnection(connection, postgres=True)
        return

    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    connection = sqlite3.connect(DB_PATH)
    try:
        yield DatabaseConnection(connection, postgres=False)
        connection.commit()
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


def using_supabase() -> bool:
    return bool(os.environ.get("SUPABASE_DB_URL", "").strip())


def init_db() -> None:
    if using_supabase():
        create_sessions = """
            CREATE TABLE IF NOT EXISTS sessions (
                source TEXT NOT NULL,
                categorie TEXT NOT NULL,
                session_id TEXT NOT NULL,
                date_examen TEXT,
                heure TEXT,
                disponibilite TEXT NOT NULL,
                quantityleft INTEGER,
                observe_a TEXT NOT NULL,
                PRIMARY KEY (source, categorie, session_id)
            )
        """
        create_alertes = """
            CREATE TABLE IF NOT EXISTS alertes (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                source TEXT NOT NULL,
                categorie TEXT NOT NULL,
                session_id TEXT NOT NULL,
                date_examen TEXT,
                heure TEXT,
                ancienne_disponibilite TEXT NOT NULL,
                nouvelle_disponibilite TEXT NOT NULL,
                detecte_a TEXT NOT NULL
            )
        """
    else:
        create_sessions = """
            CREATE TABLE IF NOT EXISTS sessions (
                source TEXT NOT NULL,
                categorie TEXT NOT NULL,
                session_id TEXT NOT NULL,
                date_examen TEXT,
                heure TEXT,
                disponibilite TEXT NOT NULL,
                quantityleft INTEGER,
                observe_a TEXT NOT NULL,
                PRIMARY KEY (source, categorie, session_id)
            )
        """
        create_alertes = """
            CREATE TABLE IF NOT EXISTS alertes (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                source TEXT NOT NULL,
                categorie TEXT NOT NULL,
                session_id TEXT NOT NULL,
                date_examen TEXT,
                heure TEXT,
                ancienne_disponibilite TEXT NOT NULL,
                nouvelle_disponibilite TEXT NOT NULL,
                detecte_a TEXT NOT NULL
            )
        """

    with connect_db() as connection:
        connection.execute(create_sessions)
        connection.execute(create_alertes)
        connection.execute(
            "CREATE INDEX IF NOT EXISTS alertes_detecte_a_idx "
            "ON alertes (detecte_a)"
        )
